def write_sqlite(path: Path, analysis: Dict[str, Any]) -> None:
    prepare_output_path(path, "SQLite artifact")
    if path.exists():
        path.unlink()
    conn: Optional[sqlite3.Connection] = None
    try:
        conn = sqlite3.connect(path)
        cur = conn.cursor()
        cur.executescript(
            """
            CREATE TABLE entities (
                row_id INTEGER PRIMARY KEY,
                entity_id TEXT,
                name TEXT,
                namespace_id TEXT,
                namespace_path TEXT,
                creation_time TEXT,
                last_update_time TEXT,
                creation_month TEXT,
                update_month TEXT,
                alias_count INTEGER,
                disabled INTEGER,
                entity_kind TEXT,
                mount_paths TEXT,
                mount_types TEXT,
                metadata TEXT
            );
            CREATE INDEX idx_entities_entity_id ON entities(entity_id);
            CREATE TABLE aliases (
                entity_id TEXT,
                namespace_id TEXT,
                alias_id TEXT,
                alias_name TEXT,
                mount_path TEXT,
                mount_type TEXT,
                creation_time TEXT,
                last_update_time TEXT
            );
            CREATE INDEX idx_aliases_entity_id ON aliases(entity_id);
            CREATE INDEX idx_aliases_alias_name ON aliases(alias_name);
            """
        )
        cur.executemany(
            """
            INSERT INTO entities (
                entity_id, name, namespace_id, namespace_path, creation_time, last_update_time,
                creation_month, update_month, alias_count, disabled, entity_kind,
                mount_paths, mount_types, metadata
            ) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)
            """,
            [
                (
                    e["entity_id"],
                    e["name"],
                    e["namespace_id"],
                    e["namespace_path"],
                    e["creation_time"].isoformat() if e["creation_time"] else None,
                    e["last_update_time"].isoformat() if e["last_update_time"] else None,
                    e["creation_month"],
                    e["update_month"],
                    e["alias_count"],
                    int(e["disabled"]),
                    e["entity_kind"],
                    ";".join(e["mount_paths"]),
                    ";".join(e["mount_types"]),
                    e["metadata"],
                )
                for e in analysis["entities"]
            ],
        )
        cur.executemany(
            "INSERT INTO aliases VALUES (?,?,?,?,?,?,?,?)",
            [
                (
                    a["entity_id"],
                    a["namespace_id"],
                    a["alias_id"],
                    a["alias_name"],
                    a["mount_path"],
                    a["mount_type"],
                    a["creation_time"],
                    a["last_update_time"],
                )
                for a in analysis["aliases"]
            ],
        )
        conn.commit()
    except sqlite3.Error as exc:
        try:
            if conn is not None:
                conn.close()
        finally:
            if path.exists():
                path.unlink()
        raise CLIError(f"Failed to write SQLite artifact {path}: {exc}") from exc
    else:
        if conn is not None:
            conn.close()


