def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Analyze Vault entity CSV exports and generate a markdown report.")
    parser.add_argument("csv", type=Path, help="Path to the entity CSV export")
    parser.add_argument("-o", "--output", type=Path, help="Path to write the markdown report (default: stdout)")
    source = parser.add_mutually_exclusive_group()
    source.add_argument("--usage-json", type=Path, help="Optional counters activity JSON for namespace names and monthly new-client reconciliation (preferred)")
    source.add_argument("--utilization-report", type=Path, help="Optional markdown report from analyze_vault_utilization.py for reconciliation (legacy; only top namespaces are mapped)")
    parser.add_argument("--window-start", help="Start month for billing-window analysis (YYYY-MM). Default: first month of the usage data, else of the CSV")
    parser.add_argument("--window-end", help="End month for billing-window analysis (YYYY-MM). Default: last month of the usage data, else of the CSV")
    parser.add_argument("--title", default="Vault Entity Inventory Analysis", help="Markdown report title")
    parser.add_argument("--top-namespaces", type=int, default=10, help="How many namespaces to show in growth tables")
    parser.add_argument("--top-aliases", type=int, default=10, help="How many redacted multi-namespace aliases to show")
    parser.add_argument("--sqlite-out", type=Path, help="Optional path to write a SQLite artifact")
    parser.add_argument("--summary-json", type=Path, help="Optional path to write a JSON summary artifact")
    args = parser.parse_args()
    for option in ("top_namespaces", "top_aliases"):
        if getattr(args, option) < 1:
            parser.error(f"--{option.replace('_', '-')} must be >= 1")
    return args


def main() -> int:
    args = parse_args()

    try:
        if args.window_start and args.window_end:
            normalize_window(args.window_start, args.window_end)
        validate_input_file(args.csv, "Entity CSV")
        if args.usage_json:
            validate_input_file(args.usage_json, "Usage JSON")
        if args.utilization_report:
            validate_input_file(args.utilization_report, "Utilization report")
        if args.output:
            prepare_output_path(args.output, "markdown report")
        if args.summary_json:
            prepare_output_path(args.summary_json, "summary JSON")

        analysis = analyze(
            csv_path=args.csv,
            utilization_report=args.utilization_report,
            window_start=args.window_start,
            window_end=args.window_end,
            top_namespaces=args.top_namespaces,
            top_aliases=args.top_aliases,
            usage_json=args.usage_json,
        )

        markdown = render_report(analysis, args.title)

        if args.output:
            args.output.write_text(markdown, encoding="utf-8")
            print(f"Report written to: {args.output}", file=sys.stderr)
        else:
            print(markdown, end="")

        if args.sqlite_out:
            write_sqlite(args.sqlite_out, analysis)
            print(f"SQLite artifact written to: {args.sqlite_out}", file=sys.stderr)

        if args.summary_json:
            payload = {k: v for k, v in analysis.items() if k not in {"entities", "aliases"}}
            args.summary_json.write_text(json.dumps(payload, indent=2), encoding="utf-8")
            print(f"Summary JSON written to: {args.summary_json}", file=sys.stderr)
    except CLIError as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 1
    except OSError as exc:
        print(f"Error: failed to write output: {exc}", file=sys.stderr)
        return 1

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
