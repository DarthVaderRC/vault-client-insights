def render_report(analysis: Dict[str, Any], title: str) -> str:
    window_total = analysis["window_count"]
    supporting = analysis["supporting_source"]
    lines: List[str] = []
    lines.append(f"# {title}")
    lines.append("")
    lines.append(f"**Primary source:** `{Path(analysis['csv_path']).name}`  ")
    if supporting:
        lines.append(f"**Supporting source:** `{Path(supporting).name}`  ")
    lines.append(f"**Generated:** {datetime.now().strftime('%d %B %Y')}")
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("## Executive Summary")
    lines.append("")
    lines.append("| Finding | Detail |")
    lines.append("|---------|--------|")
    lines.append(
        f"| **Entity creations in the reporting window** | **{fmt_int(window_total)}** of {fmt_int(analysis['entity_count'])} entities were created between **{analysis['window_start']}** and **{analysis['window_end']}**. |"
    )
    if supporting and analysis["report_namespace_total"] is not None:
        lines.append(
            f"| **Window reconciliation** | The CSV spans **{fmt_int(analysis['namespace_count_csv'])}** namespace IDs overall, with **{fmt_int(analysis['window_namespaces'])}** showing creations inside the analysis window versus **{fmt_int(analysis['report_namespace_total'])}** namespaces in the supporting source. |"
        )
    top_mounts = sorted(analysis["window_mount_counts"].items(), key=lambda kv: (kv[1], kv[0]), reverse=True)[:2]
    if top_mounts:
        drivers = "; ".join(f"`{mp}` contributed **{fmt_int(c)} ({fmt_pct(c, window_total)})**" for mp, c in top_mounts)
        lines.append(f"| **Growth driver** | {drivers} of window entity creation. |")
    lines.append(
        f"| **Cross-namespace reuse** | **{fmt_int(analysis['email_multi_namespace_aliases_count'])}** distinct email aliases appear in multiple namespaces, accounting for **{fmt_int(analysis['email_multi_namespace_entities'])}** entity rows and **{fmt_int(analysis['email_multi_namespace_extra_presences'])}** extra namespace presences beyond the first namespace. |"
    )
    if analysis["updated_later_count"] == 0:
        update_note = "no entity was updated after creation, so this export behaves like a creation-time inventory, not an update-history feed."
    else:
        update_note = f"{fmt_pct(analysis['updated_later_count'], analysis['entity_count'])} of entities were modified after creation (for example alias, policy or metadata changes)."
    lines.append(
        f"| **`last_update_time` signal** | **{fmt_int(analysis['updated_later_count'])}** entities show `last_update_time > creation_time`; {update_note} |"
    )
    lines.append("")
    lines.append("---")
    lines.append("")

    if supporting:
        lines.append("## Monthly Growth Comparison")
        lines.append("")
        lines.append("| Month | Supporting source: new clients | CSV: entities created | Delta | Top creation namespace | Top creation mount |")
        lines.append("|-------|-------------------------------:|----------------------:|------:|------------------------|-------------------|")
        for row in analysis["monthly_comparison"]:
            report_value = row["report_new_clients"]
            report_str = fmt_int(report_value) if report_value is not None else "n/a"
            delta_str = f"{row['created_entities'] - report_value:+d}" if report_value is not None else "n/a"
            mount_label = f"`{row['top_create_mount']}`" if row["top_create_mount"] else "-"
            namespace_label = row["top_create_namespace"] or "-"
            lines.append(
                f"| {row['label']} | {report_str} | {fmt_int(row['created_entities'])} | {delta_str} | {namespace_label} | {mount_label} |"
            )
        lines.append("")
        lines.append("New clients are entities (and non-entity tokens) that were first active in a month, while this CSV counts entity records by creation month. Entities that exist but never authenticate in the billing period are not clients, and non-entity tokens never appear in the CSV, so deltas are expected.")
        lines.append("")
        lines.append("---")
        lines.append("")

    lines.append("## Top Namespaces Driving Growth")
    lines.append("")
    lines.append("| Rank | Namespace | Entities created in window | % of window |")
    lines.append("|------|-----------|--------------------------:|------------:|")
    for index, item in enumerate(analysis["top_creation_namespaces_window"], start=1):
        lines.append(f"| {index} | {item['namespace']} | {fmt_int(item['count'])} | {fmt_pct(item['count'], window_total)} |")
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("## Cross-Namespace Identity Presence")
    lines.append("")
    lines.append("| Metric | Value |")
    lines.append("|--------|------:|")
    lines.append(f"| Distinct alias names | {fmt_int(analysis['distinct_alias_names'])} |")
    lines.append(f"| Distinct email aliases | {fmt_int(analysis['distinct_email_aliases'])} |")
    lines.append(f"| Multi-namespace aliases (all types) | {fmt_int(analysis['multi_namespace_aliases_count'])} |")
    lines.append(f"| Multi-namespace aliases (email only) | {fmt_int(analysis['email_multi_namespace_aliases_count'])} |")
    lines.append(f"| Entity rows backed by multi-namespace email aliases | {fmt_int(analysis['email_multi_namespace_entities'])} |")
    lines.append(f"| Extra namespace presences from multi-namespace email aliases | {fmt_int(analysis['email_multi_namespace_extra_presences'])} |")
    lines.append("")
    if analysis["mount_alias_spread"]:
        lines.append("### Alias spread by mount path")
        lines.append("")
        lines.append("An alias counts toward every mount path it appears on. The same mount path in different namespaces is a different mount, so this shows where the same identity is set up repeatedly.")
        lines.append("")
        lines.append("| Mount path | Distinct aliases | Email aliases | Aliases in 2+ namespaces |")
        lines.append("|------------|-----------------:|--------------:|-------------------------:|")
        for item in analysis["mount_alias_spread"]:
            lines.append(
                f"| `{item['mount_path']}` | {fmt_int(item['distinct_aliases'])} | {fmt_int(item['distinct_email_aliases'])} | {fmt_int(item['multi_namespace_aliases'])} |"
            )
        lines.append("")
    lines.append("### High-spread aliases (redacted)")
    lines.append("")
    lines.append("| Redacted alias | Namespaces | Entities | Mount paths |")
    lines.append("|----------------|-----------:|---------:|-------------|")
    for item in analysis["top_multi_namespace_aliases"]:
        mount_paths = ", ".join(f"`{p}`" for p in item["mount_paths"]) if item["mount_paths"] else "-"
        lines.append(f"| `{item['alias']}` | {item['namespaces']} | {item['entities']} | {mount_paths} |")
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("## Duplicate and Hygiene Checks")
    lines.append("")
    lines.append("| Check | Result |")
    lines.append("|-------|-------:|")
    for key, label in [
        ("exact_duplicate_entity_ids", "Exact duplicate entity IDs"),
        ("exact_duplicate_names", "Exact duplicate entity names"),
        ("exact_duplicate_alias_ids", "Exact duplicate alias IDs"),
        ("same_alias_same_namespace_mount_groups", "Same alias in same namespace + same mount"),
        ("same_alias_same_namespace_groups", "Same alias in same namespace (any mount)"),
    ]:
        lines.append(f"| {label} | {analysis['duplicate_metrics'][key]} |")
    lines.append(f"| Disabled entities | {fmt_int(analysis['disabled_count'])} |")
    lines.append("")
    if analysis["same_namespace_examples"]:
        lines.append("### Same-namespace repeat examples (redacted)")
        lines.append("")
        lines.append("| Alias | Namespace ID | Entities | Mount paths |")
        lines.append("|-------|--------------|---------:|-------------|")
        for item in analysis["same_namespace_examples"]:
            mount_paths = ", ".join(f"`{p}`" for p in item["mount_paths"]) if item["mount_paths"] else "-"
            lines.append(f"| `{item['alias']}` | `{item['namespace_id']}` | {item['entities']} | {mount_paths} |")
        lines.append("")
        lines.append("---")
        lines.append("")

    lines.append("## `last_update_time` Interpretation")
    lines.append("")
    lines.append(f"- Entities updated after creation: **{fmt_int(analysis['updated_later_count'])}**")
    lines.append(f"- Entities never updated after creation: **{fmt_int(analysis['never_updated_count'])}**")
    if analysis["updated_later_count"] == 0:
        lines.append("- In this export, `last_update_time` is identical to `creation_time` for every row, so it does not add a separate churn or lifecycle signal.")
    else:
        lines.append("- `last_update_time` changes when the entity record is modified. It is not a last-login or last-seen time, so it cannot show whether an entity is still active.")
    lines.append("")

    if analysis["post_window_count"]:
        lines.append("---")
        lines.append("")
        lines.append("## Post-Window Growth")
        lines.append("")
        lines.append(
            f"There are **{fmt_int(analysis['post_window_count'])}** entities created after the analysis window. "
            f"Top namespaces in the first post-window month ({month_label(analysis['first_post_window_month'])}):"
        )
        lines.append("")
        lines.append("| Namespace ID | Entities |")
        lines.append("|--------------|---------:|")
        for item in analysis["first_post_window_top"]:
            lines.append(f"| `{item['namespace_id']}` | {fmt_int(item['count'])} |")
        lines.append("")

    lines.append("---")
    lines.append("")
    lines.append("## Follow-Up Questions")
    lines.append("")
    questions = []
    if top_mounts:
        questions.append(
            f"`{top_mounts[0][0]}` drives most entity creation in the window. Is that expected, and are its identities people or shared service identities?"
        )
    if analysis["email_multi_namespace_aliases_count"]:
        questions.append(
            "The same email identities exist in several namespaces. Would a shared auth mount in a parent namespace (with entities defined once) fit the operating model?"
        )
    questions.append("Is there a source of last-login or last-seen activity, since `last_update_time` only reflects record changes?")
    for index, question in enumerate(questions, start=1):
        lines.append(f"{index}. {question}")
    lines.append("")
    return "\n".join(lines) + "\n"


